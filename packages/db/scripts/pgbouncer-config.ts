/**
 * PgBouncer's local configuration, written by `pnpm db:setup` (spec 0017 D2, D5, PB9).
 *
 *   .pgbouncer/userlist.txt         the auth_file: SCRAM verifiers only, never passwords; owner-only
 *   .pgbouncer/pgbouncer.probe.ini  the probe profile (default_pool_size 2)
 *   .pgbouncer/pgbouncer.suite.ini  the suite profile (default_pool_size 10)
 *
 * The directory is git-ignored. The container mounts the files read-only at /etc/pgbouncer/.
 * Pure functions here; setup-local.ts does the database and file work.
 */
import { createHash, createHmac, pbkdf2Sync, randomBytes } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import {
  closeSync,
  fchmodSync,
  fsyncSync,
  openSync,
  renameSync,
  rmSync,
  statSync,
  writeSync,
} from 'node:fs';
import { userInfo } from 'node:os';
import { basename, dirname, join } from 'node:path';

/** The admin console's user: an auth_file entry only, never a PostgreSQL role (PB9). */
export const PGBOUNCER_ADMIN = 'pgbouncer_admin';
/** Published on loopback only (`-p 127.0.0.1:6432:6432`). */
export const PGBOUNCER_PORT = 6432;
/** Where PgBouncer reaches Postgres from its bridge container (`--add-host=host.docker.internal:host-gateway`). */
export const PGBOUNCER_SERVER_HOST = 'host.docker.internal';

export type Profile = 'probe' | 'suite';
/** D5: the only difference between the two profiles. */
export const POOL_SIZE: Readonly<Record<Profile, number>> = { probe: 2, suite: 10 };

/** PostgreSQL's SCRAM-SHA-256 verifier: `SCRAM-SHA-256$<iterations>:<salt>$<StoredKey>:<ServerKey>`. */
const B64 = '[A-Za-z0-9+/]+={0,2}';
const SCRAM_VERIFIER = new RegExp(`^SCRAM-SHA-256\\$[1-9][0-9]*:${B64}\\$${B64}:${B64}$`);
const ROLE_NAME = /^[a-z_][a-z0-9_]*$/;

/**
 * A SCRAM-SHA-256 verifier in PostgreSQL's format (RFC 5802/7677), for the admin entry, which has no PostgreSQL role
 * to copy one from. App roles' verifiers are always copied from pg_authid, never computed here.
 * The password must be ASCII without spaces or controls, so SASLprep leaves it unchanged.
 */
export function scramVerifier(password: string, salt = randomBytes(16), iterations = 4096): string {
  if (!/^[\x21-\x7e]+$/.test(password))
    throw new Error('scramVerifier: the password must be printable ASCII');
  const salted = pbkdf2Sync(password, salt, iterations, 32, 'sha256');
  const clientKey = createHmac('sha256', salted).update('Client Key').digest();
  const storedKey = createHash('sha256').update(clientKey).digest();
  const serverKey = createHmac('sha256', salted).update('Server Key').digest();
  return `SCRAM-SHA-256$${iterations}:${salt.toString('base64')}$${storedKey.toString('base64')}:${serverKey.toString('base64')}`;
}

/**
 * The auth_file: one `"user" "verifier"` line per entry. Fails, naming the user but never the value, on a name that
 * isn't a plain role name, a duplicate, or anything that isn't a SCRAM-SHA-256 verifier (an md5 hash, a plaintext
 * password, a missing password), so a password can never be written into the file.
 */
export function renderAuthFile(
  entries: readonly { user: string; verifier: string | null }[],
): string {
  const seen = new Set<string>();
  const lines = entries.map(({ user, verifier }) => {
    if (!ROLE_NAME.test(user))
      throw new Error(`auth file: unsafe user name ${JSON.stringify(user)}`);
    if (seen.has(user)) throw new Error(`auth file: ${user} appears twice`);
    seen.add(user);
    if (verifier === null || !SCRAM_VERIFIER.test(verifier))
      throw new Error(
        `auth file: ${user} has no SCRAM-SHA-256 verifier (is password_encryption scram-sha-256?)`,
      );
    return `"${user}" "${verifier}"`;
  });
  if (lines.length === 0) throw new Error('auth file: no entries');
  return `${lines.join('\n')}\n`;
}

/**
 * pgbouncer.ini for a profile (spec 0017 Design). `[databases]` entries carry no `user=`: SCRAM pass-through needs the
 * connecting user's own name and matching secrets (PB9). `ignore_startup_parameters` stays unset and
 * `max_packet_size` at its default (revision 5: clear of CVE-2026-107349's and CVE-2026-107348's conditions).
 */
export function renderIni(opts: {
  profile: Profile;
  databases: readonly string[];
  serverPort: number;
}): string {
  const { profile, databases, serverPort } = opts;
  if (!(profile in POOL_SIZE)) throw new Error(`unknown profile ${profile}`);
  if (!Number.isInteger(serverPort) || serverPort < 1 || serverPort > 65535)
    throw new Error(`bad port ${serverPort}`);
  if (databases.length === 0) throw new Error('no databases');
  for (const d of databases)
    if (!ROLE_NAME.test(d)) throw new Error(`unsafe database name ${JSON.stringify(d)}`);
  return [
    `; Generated by pnpm db:setup (spec 0017), ${profile} profile — LOCAL DEVELOPMENT AND CI ONLY.`,
    '[databases]',
    ...databases.map((d) => `${d} = host=${PGBOUNCER_SERVER_HOST} port=${serverPort} dbname=${d}`),
    '',
    '[pgbouncer]',
    'listen_addr = 0.0.0.0',
    `listen_port = ${PGBOUNCER_PORT}`,
    'unix_socket_dir =', // the root filesystem is read-only
    'auth_type = scram-sha-256',
    'auth_file = /etc/pgbouncer/userlist.txt',
    `admin_users = ${PGBOUNCER_ADMIN}`,
    'pool_mode = transaction',
    `default_pool_size = ${POOL_SIZE[profile]}`,
    'max_client_conn = 200',
    'max_prepared_statements = 0',
    'query_wait_timeout = 2',
    'server_round_robin = 0',
    '',
  ].join('\n');
}

// ---------- owner-only file permissions (PB9) ----------

/** `icacls <file>` output → its ACEs as `principal:(rights)` strings (the file name is stripped from the first). */
export function parseIcacls(output: string, file: string): string[] {
  const aces: string[] = [];
  for (const raw of output.split(/\r?\n/)) {
    let line = raw.trim();
    if (!line || /^Successfully processed|^Failed processing/i.test(line)) continue;
    if (line.toLowerCase().startsWith(file.toLowerCase())) line = line.slice(file.length).trim();
    if (line) aces.push(line);
  }
  return aces;
}

/** Problems with an ACL that should grant only `user` full control, with nothing inherited. */
export function windowsAclProblems(aces: readonly string[], user: string): string[] {
  const expected = `${user}:(F)`.toLowerCase();
  if (aces.length === 1 && aces[0]?.toLowerCase() === expected) return [];
  return [
    `the ACL must be exactly "${user}:(F)" with inheritance removed; it has: ${aces.join('; ') || 'nothing'}`,
  ];
}

/** Problems with a POSIX mode/owner that should be the current user only, mode 0600. */
export function posixModeProblems(mode: number, uid: number, currentUid: number): string[] {
  const problems: string[] = [];
  if ((mode & 0o777) !== 0o600)
    problems.push(`mode is ${(mode & 0o777).toString(8).padStart(4, '0')}, expected 0600`);
  if (uid !== currentUid)
    problems.push(`owned by uid ${uid}, not the current user (${currentUid})`);
  return problems;
}

/**
 * The current Windows account as icacls names it (`DOMAIN\user`). Not `whoami`: under Git Bash that resolves to
 * MSYS's, which prints the bare name, and the grant and the check must use the same name.
 */
function windowsUser(): string {
  const domain = process.env.USERDOMAIN;
  if (!domain) throw new Error('USERDOMAIN is not set: cannot name the current Windows account');
  return `${domain}\\${userInfo().username}`;
}

/** The filesystem and command operations the owner-only writer uses; replaced in tests to pin their order. */
export interface OwnerOnlyOps {
  platform: NodeJS.Platform;
  /** Creates `path` exclusively (fails if it exists), mode 0600, empty; returns a descriptor. */
  createExclusive(path: string): number;
  /** POSIX only: sets the open file's mode (never widens: the file was created 0600 and is still empty). */
  fchmod(fd: number, mode: number): void;
  write(fd: number, content: string): void;
  fsync(fd: number): void;
  close(fd: number): void;
  /** Atomically replaces `to` with `from` (same directory). */
  rename(from: string, to: string): void;
  unlink(path: string): void;
  /** POSIX only. */
  stat(path: string): { mode: number; uid: number };
  uid(): number;
  /** Windows only: icacls with these arguments; returns its output. */
  icacls(args: string[]): string;
  windowsUser(): string;
  random(): string;
}

export const realOwnerOnlyOps: OwnerOnlyOps = {
  platform: process.platform,
  createExclusive: (path) => openSync(path, 'wx', 0o600),
  fchmod: (fd, mode) => {
    fchmodSync(fd, mode);
  },
  write: (fd, content) => {
    writeSync(fd, content);
  },
  fsync: (fd) => {
    fsyncSync(fd);
  },
  close: (fd) => {
    closeSync(fd);
  },
  rename: (from, to) => {
    renameSync(from, to);
  },
  unlink: (path) => {
    rmSync(path, { force: true });
  },
  stat: (path) => statSync(path),
  uid: () => {
    if (!process.getuid) throw new Error('no POSIX user id on this platform');
    return process.getuid();
  },
  icacls: (args) => execFileSync('icacls', args, { encoding: 'utf8' }),
  windowsUser,
  random: () => randomBytes(8).toString('hex'),
};

/** Problems with `file`'s permissions, read only: nothing here changes them. */
export function ownerOnlyProblems(file: string, ops: OwnerOnlyOps = realOwnerOnlyOps): string[] {
  if (ops.platform === 'win32')
    return windowsAclProblems(parseIcacls(ops.icacls([file]), file), ops.windowsUser());
  const st = ops.stat(file);
  return posixModeProblems(st.mode, st.uid, ops.uid());
}

/**
 * Writes `content` to `target` readable by the current user only (PB9), so that no file holding it is ever wider:
 *   1. a fresh temporary file beside `target`, created exclusively, 0600 and empty;
 *   2. narrowed while still empty (Windows: inheritance removed, the current account granted; nothing to reset on a
 *      new file), and checked;
 *   3. the content written and flushed, then the permissions checked again, read only;
 *   4. renamed over `target` atomically, and the result checked, read only.
 * A reader holding the old `target` open keeps the old file and never sees the new content. Nothing that changes
 * permissions runs after the content is written. A failure before the rename removes the temporary file and leaves
 * `target` as it was; a failed final check throws, failing the run.
 */
export function writeOwnerOnly(
  target: string,
  content: string,
  ops: OwnerOnlyOps = realOwnerOnlyOps,
): void {
  const tmp = join(dirname(target), `.${basename(target)}.${ops.random()}.tmp`);
  const fail = (where: string, problems: string[]) => {
    if (problems.length) throw new Error(`${where}: ${problems.join('; ')}`);
  };
  const fd = ops.createExclusive(tmp);
  let open = true;
  let renamed = false;
  try {
    if (ops.platform === 'win32') {
      ops.icacls([tmp, '/inheritance:r', '/grant:r', `${ops.windowsUser()}:F`]);
    } else {
      ops.fchmod(fd, 0o600);
    }
    fail(`${tmp} (empty)`, ownerOnlyProblems(tmp, ops));
    ops.write(fd, content);
    ops.fsync(fd);
    ops.close(fd);
    open = false;
    fail(tmp, ownerOnlyProblems(tmp, ops));
    ops.rename(tmp, target);
    renamed = true;
    fail(target, ownerOnlyProblems(target, ops));
  } finally {
    if (open) ops.close(fd);
    if (!renamed) ops.unlink(tmp);
  }
}
